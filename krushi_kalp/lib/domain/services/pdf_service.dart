class PdfService {
  // Maintaining a public constructor for existing usage
  PdfService();

  static final PdfService instance = PdfService();

  /// Main method to generate a professional exam result PDF.
  Future<File> generateExamResultPdf({
    required String testId,
    required String testTitle,
    required double score,
    required double totalMarks,
    required int correctAnswers,
    required int wrongAnswers,
    required int skippedAnswers,
    required String userId,
    required String userName,
    List<Question>? questions,
    Map<int, int>? selectedAnswers,
    String languageCode = 'en',
  }) async {
    final pdf = pw.Document(
      author: 'Krushi Kalp',
      title: 'Exam Result - $testTitle',
      subject: 'Mock Test Result Analysis',
      keywords: 'krushi kalp, agriculture, mock test, result',
    );

    // Load Fonts - Force Unicode for everything to avoid path/height errors
    final primaryFont = await _loadFont(languageCode);
    final fallbackFont = await _loadFont('gu', forceGujarati: true);

    // Procedural widget list building
    final List<pw.Widget> buildList = [];

    // 1. Header
    buildList.add(_buildPremiumHeader(
      testTitle,
      score,
      totalMarks,
      correctAnswers,
      wrongAnswers,
      skippedAnswers,
      primaryFont,
      fallbackFont,
    ));

    // 2. Detailed Analysis Title
    if (questions != null && questions.isNotEmpty) {
      buildList.add(pw.SizedBox(height: 15));
      buildList.add(
        pw.Text(
          'Detailed Analysis',
          style: pw.TextStyle(
            fontSize: 14,
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.black,
            font: primaryFont,
            fontFallback: [fallbackFont],
          ),
        ),
      );
      buildList.add(pw.SizedBox(height: 8));

      // 3. Question Widgets (Exploded list for zero-gap pagination)
      for (var i = 0; i < questions.length; i++) {
        final q = questions[i];
        final selectedIdx = selectedAnswers?[i];
        buildList.addAll(_buildAnalysisWidgetList(
          i + 1,
          q,
          selectedIdx,
          primaryFont,
          fallbackFont,
        ));
      }
    }

    // 4. Final Footer
    buildList.add(pw.SizedBox(height: 20));
    buildList.add(
      pw.Center(
        child: pw.Text(
          'Generated by Krushi Kalp App',
          style: pw.TextStyle(
            color: PdfColors.grey500,
            fontSize: 10,
            font: primaryFont,
            fontFallback: [fallbackFont],
          ),
        ),
      ),
    );

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(35),
        theme: pw.ThemeData.withFont(
          base: primaryFont,
          bold: primaryFont,
          italic: primaryFont,
        ).copyWith(
          defaultTextStyle: pw.TextStyle(
            font: primaryFont,
            fontFallback: [fallbackFont],
          ),
        ),
        footer: (pw.Context context) => pw.Container(
          height: 30,
          width: double.infinity,
          alignment: pw.Alignment.bottomRight,
          child: pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: pw.TextStyle(
              color: PdfColors.grey500,
              fontSize: 9,
              font: primaryFont,
              fontFallback: [fallbackFont],
            ),
          ),
        ),
        build: (pw.Context context) => buildList,
      ),
    );

    final dir = await getTemporaryDirectory();
    final file = File("${dir.path}/result_$testId.pdf");
    await file.writeAsBytes(await pdf.save());
    return file;
  }

  pw.Widget _buildPremiumHeader(
    String title,
    double score,
    double totalMarks,
    int correct,
    int wrong,
    int skipped,
    pw.Font primaryFont,
    pw.Font fallbackFont,
  ) {
    final double percentage = (score / totalMarks) * 100;
    final bool isPassed = percentage >= 35;
    final PdfColor brandBlue = PdfColor.fromInt(0xFF3399FF);
    final PdfColor statRed = PdfColor.fromInt(0xFFF44336);

    return pw.Column(
      children: [
        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.symmetric(vertical: 5),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('KRUSHI KALP',
                  style: pw.TextStyle(
                      fontWeight: pw.FontWeight.bold,
                      fontSize: 8,
                      color: PdfColors.grey600,
                      font: primaryFont,
                      fontFallback: [fallbackFont])),
              pw.Text(
                  '${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                  style: pw.TextStyle(
                      fontSize: 8,
                      color: PdfColors.grey600,
                      font: primaryFont,
                      fontFallback: [fallbackFont])),
            ],
          ),
        ),
        pw.Container(
          width: double.infinity,
          margin: const pw.EdgeInsets.symmetric(vertical: 10),
          padding: const pw.EdgeInsets.symmetric(horizontal: 20, vertical: 15),
          decoration: pw.BoxDecoration(
            color: brandBlue,
            borderRadius: const pw.BorderRadius.all(pw.Radius.circular(10)),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('REPORT SUMMARY',
                      style: pw.TextStyle(
                          color: PdfColors.white,
                          fontSize: 8,
                          fontWeight: pw.FontWeight.bold,
                          font: primaryFont,
                          fontFallback: [fallbackFont])),
                  pw.SizedBox(height: 2),
                  pw.Row(
                    crossAxisAlignment: pw.CrossAxisAlignment.end,
                    children: [
                      pw.Text('${percentage.toStringAsFixed(1)}%',
                          style: pw.TextStyle(
                              fontSize: 26,
                              fontWeight: pw.FontWeight.bold,
                              color: PdfColors.white,
                              font: primaryFont,
                              fontFallback: [fallbackFont])),
                      pw.SizedBox(width: 5),
                      pw.Text('PASS SCORE',
                          style: pw.TextStyle(
                              color: PdfColors.white.withAlpha(0.7),
